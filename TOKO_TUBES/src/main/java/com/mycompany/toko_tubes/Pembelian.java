   private boolean cekNamaBarang(String namaBarang) throws SQLException {
    String query = "SELECT COUNT(*) AS jumlah FROM barang WHERE nama_barang = ?";
    try (PreparedStatement pst = connection.prepareStatement(query)) {
        pst.setString(1, namaBarang);
        ResultSet rs = pst.executeQuery();
        if (rs.next()) {
            int jumlah = rs.getInt("jumlah");
            return jumlah > 0; // Mengembalikan true jika nama barang sudah ada dalam database
        }
    } catch (SQLException ex) {
        ex.printStackTrace(); // Tangani pengecualian SQL
    }
    return false; // Jika terjadi kesalahan, mengembalikan false secara default
    }   
        
