private double TotalPembelian() {
    double total = 0.0;
    for (int i = 0; i < jTable1.getRowCount(); i++) {
        double subtotal = Double.parseDouble(jTable1.getValueAt(i, 4).toString());
        total += subtotal;
    }
    return total;
}

private void restock(int id_barang, double jumlahBarang) throws SQLException {
    String updateQuery = "UPDATE barang SET stok = stok + ? WHERE id_barang = ?";
    try (PreparedStatement updateStatement = connection.prepareStatement(updateQuery)) {
        updateStatement.setDouble(1, jumlahBarang);
        updateStatement.setInt(2, id_barang);
        updateStatement.executeUpdate();
    }
}
