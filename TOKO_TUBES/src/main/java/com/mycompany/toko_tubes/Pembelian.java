private void DataTransaksi(int IDPetugas) throws SQLException {
    connection.setAutoCommit(false);
    
    double totalPembelian = TotalPembelian();
    
    String insertTransaksiQuery = "INSERT INTO transaksi_pembelian (tanggal_transaksi, total_pembelian, id_petugas, id_suplier) VALUES (NOW(), ?, ?, ?)";
    PreparedStatement insertTransaksiStatement = connection.prepareStatement(insertTransaksiQuery, Statement.RETURN_GENERATED_KEYS);
    insertTransaksiStatement.setDouble(1, totalPembelian);
    insertTransaksiStatement.setInt(2, IDPetugas);
    
    for (int i = 0; i < jTable1.getRowCount(); i++) {
        String supplierName = jTable1.getValueAt(i, 0).toString(); // Nama supplier dari kolom pertama
        String namaBarang = jTable1.getValueAt(i, 1).toString();   // Nama barang dari kolom kedua
        double hargaBarang = Double.parseDouble(jTable1.getValueAt(i, 2).toString());
        double jumlahBarang = Double.parseDouble(jTable1.getValueAt(i, 3).toString());
        double subtotal = Double.parseDouble(jTable1.getValueAt(i, 4).toString());
 
        int id_supplier = getSupplierID(supplierName);
        insertTransaksiStatement.setDouble(1, totalPembelian);
        insertTransaksiStatement.setInt(2, IDPetugas);
        insertTransaksiStatement.setInt(3, id_supplier);
        insertTransaksiStatement.executeUpdate();

        ResultSet generatedKeys = insertTransaksiStatement.getGeneratedKeys();
        int id_transaksi_pembelian = -1;
        if (generatedKeys.next()) {
            id_transaksi_pembelian = generatedKeys.getInt(1);
        } else {
            throw new SQLException("Creating transaction failed, no ID obtained.");
        }
        
        // Mendapatkan ID barang dari database berdasarkan nama barang
        String sql = "SELECT id_barang FROM barang WHERE nama_barang = ?";
        PreparedStatement ps = connection.prepareStatement(sql);
        ps.setString(1, namaBarang);
        ResultSet rs = ps.executeQuery();
        
        int id_barang = -1;
        if (rs.next()) {
            id_barang = rs.getInt("id_barang"); // Mengambil ID barang dari hasil query
        } else {
            throw new SQLException("Barang not found in database: " + namaBarang);
        }
     
        InsertDetailTransaksi(id_transaksi_pembelian, id_barang, jumlahBarang, subtotal);
        restock(id_barang, jumlahBarang);
        JOptionPane.showMessageDialog(this, "Transaction data has been saved successfully!");
    }
    
    connection.commit();
}

private int getSupplierID(String namaSupplier) throws SQLException {
    String sql = "SELECT id_suplier FROM suplier WHERE nama_suplier = ?";
    PreparedStatement ps = connection.prepareStatement(sql);
    ps.setString(1, namaSupplier);
    ResultSet rs = ps.executeQuery();

    if (rs.next()) {
        return rs.getInt("id_suplier"); 
    } else {
        String insertSupplierQuery = "INSERT INTO suplier (nama_suplier) VALUES (?)";
        PreparedStatement insertSupplierStatement = connection.prepareStatement(insertSupplierQuery, Statement.RETURN_GENERATED_KEYS);
        insertSupplierStatement.setString(1, namaSupplier);
        insertSupplierStatement.executeUpdate();

        ResultSet generatedKeys = insertSupplierStatement.getGeneratedKeys();
        if (generatedKeys.next()) {
            return generatedKeys.getInt(1); 
        } else {
            throw new SQLException("Failed to add new supplier.");
        }
    }
}


